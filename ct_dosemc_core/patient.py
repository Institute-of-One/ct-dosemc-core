#: The patient dose grid, isotropic. See the module docstring for why 2.5 mm.
DOSE_GRID_MM = 2.5

#: Bone HU range of the Schneider group table. Volume fraction f is linear in HU
#: on this interval because HU ∝ μ and μ is linear in volume fraction.
BONE_START_HU = 100.0
BONE_TOP_HU = CALIBRATION_MAX_HU  # 3000
N_BONE_BINS = 11
#: Edges uniform in ``f ** (1/power)``. power=1 is equal-HU; power=2 (default)
#: is uniform in √f, which puts the narrowest bins at the soft-tissue boundary
#: the scored organs actually sit on. Equal-HU bins put the largest relative
#: μ error exactly there (half-bin width 1/(2n) = 0.0625 at n=8).
BONE_BIN_POWER = 2.0

#: In-plane box that reaches the focal spot (G3). 2 × 60 cm SAD + 10 cm = 130 cm.
DEFAULT_SAD_CM = 60.0
FOCAL_BOX_XY_CM = 130.0


def bone_bin_edges(
    n_bins: int = N_BONE_BINS,
    *,
    start_hu: float = BONE_START_HU,
    top_hu: float = BONE_TOP_HU,
    power: float = BONE_BIN_POWER,
) -> np.ndarray:
    """HU edges of the graded bone table; shared by ``--bones N`` and the group list.

    ``power=1`` is equal-HU. The default ``power=2`` is uniform in √f, so the
    first bin is narrower by a factor of n (half-width 1/(2 n^2) in f rather
    than 1/(2n)). Scored organs are soft tissue; the photoelectric residual a
    reviewer probes is at this low-f edge, and equal-HU bins maximise the
    relative error exactly there.
    """
    if n_bins < 1:
        raise ValueError("need at least one bone bin")
    if power <= 0.0:
        raise ValueError("bone-bin power must be positive")
    i = np.arange(n_bins + 1, dtype=float)
    f = (i / n_bins) ** float(power)
    return float(start_hu) + (float(top_hu) - float(start_hu)) * f


def bone_volume_fraction(
    hu: float | np.ndarray,
    *,
    start_hu: float = BONE_START_HU,
    top_hu: float = BONE_TOP_HU,
) -> np.ndarray:
    """Volume fraction of cortical bone, linear in HU.

    μ_mix = (1−f) μ_soft + f μ_bone, and HU ∝ μ, so f (not the weight fraction)
    is what belongs on a linear HU axis. Clipped to [0, 1].
    """
    span = float(top_hu) - float(start_hu)
    f = (np.asarray(hu, dtype=float) - float(start_hu)) / span
    return np.clip(f, 0.0, 1.0)


def bone_bin_volume_fraction(
    hu: float | np.ndarray,
    n_bins: int = N_BONE_BINS,
    *,
    start_hu: float = BONE_START_HU,
    top_hu: float = BONE_TOP_HU,
    power: float = BONE_BIN_POWER,
) -> np.ndarray:
    """Volume fraction of the discrete bin that contains ``hu`` (the bin midpoint)."""
    edges = bone_bin_edges(n_bins, start_hu=start_hu, top_hu=top_hu, power=power)
    h = np.asarray(hu, dtype=float)
    # searchsorted right-1 so a point on an interior edge belongs to the higher bin,
    # matching assign_material_index (hu_low inclusive, next hu_low exclusive).
    idx = np.clip(np.searchsorted(edges, h, side="right") - 1, 0, n_bins - 1)
    mid = 0.5 * (edges[idx] + edges[idx + 1])
    return bone_volume_fraction(mid, start_hu=start_hu, top_hu=top_hu)


def mix_by_volume_fraction(
    soft: Sequence[tuple[int, float]],
    bone: Sequence[tuple[int, float]],
    f: float,
    rho_soft: float,
    rho_bone: float,
) -> tuple[list[tuple[int, float]], float, float]:
    """Mix two materials by **volume** fraction ``f`` of the bone endpoint.

    Returns ``(elemental_weight_fractions, rho_mix, w_bone)`` where

        rho_mix = (1−f) rho_soft + f rho_bone
        w_bone  = f * rho_bone / rho_mix

    and the elemental weight fractions follow from ``w_bone``. Mixing *weight*
    fractions linearly with HU understates the bone component: at f = 0.5,
    rho_soft = 1.03, rho_bone = 1.92 the bone weight fraction is 0.651, not 0.500.
    """
    f = float(f)
    if not 0.0 <= f <= 1.0:
        raise ValueError(f"volume fraction must lie in [0, 1], got {f}")
    if rho_soft <= 0.0 or rho_bone <= 0.0:
        raise ValueError("endpoint densities must be positive")
    rho_mix = (1.0 - f) * float(rho_soft) + f * float(rho_bone)
    w_bone = (f * float(rho_bone) / rho_mix) if rho_mix else 0.0
    w: dict[int, float] = {}
    for z, frac in soft:
        w[int(z)] = w.get(int(z), 0.0) + (1.0 - w_bone) * float(frac)
    for z, frac in bone:
        w[int(z)] = w.get(int(z), 0.0) + w_bone * float(frac)
    total = sum(w.values())
    fractions = [(z, w[z] / total) for z in sorted(w)]
    return fractions, float(rho_mix), float(w_bone)


def _mu_over_rho_nist(fractions: Sequence[tuple[int, float]], energy_kev: float) -> float:
    """Mass attenuation coefficient of a mixture at one energy, NIST via SpekPy."""
    from spekpy import SpekTools as st

    mu_data, _muen_air, _ = st.load_mu_data("nist")
    e = np.asarray([float(energy_kev)])
    acc = 0.0
    for z, w in fractions:
        mu_over_rho = float(np.asarray(mu_data.get_mu_over_rho(int(z), e))[0])
        acc += float(w) * mu_over_rho
    return acc


def bone_discretization_error(
    soft: Sequence[tuple[int, float]],
    bone: Sequence[tuple[int, float]],
    rho_soft: float,
    rho_bone: float,
    *,
    n_bins: int = N_BONE_BINS,
    start_hu: float = BONE_START_HU,
    top_hu: float = BONE_TOP_HU,
    energy_kev: float = 60.0,
    n_samples: int = 2901,
    power: float = BONE_BIN_POWER,
) -> dict:
    """Max relative |μ_binned − μ_continuous| / μ_continuous at ``energy_kev``.

    No Monte Carlo: μ = ρ_Schneider(HU) × (μ/ρ)_mix. (μ/ρ) of a two-material mix
    is linear in the *weight* fraction, which is the nonlinear map of volume
    fraction f(HU). The voxel density is the same for (a) and (b), so the
    relative error is that of (μ/ρ). NIST coefficients via SpekPy, two endpoint
    evaluations, then a fine HU grid.
    """
    mu_s = _mu_over_rho_nist(soft, energy_kev)
    mu_b_end = _mu_over_rho_nist(bone, energy_kev)
    hu = np.linspace(float(start_hu), float(top_hu), int(n_samples))
    f_cont = bone_volume_fraction(hu, start_hu=start_hu, top_hu=top_hu)
    f_bin = bone_bin_volume_fraction(
        hu, n_bins, start_hu=start_hu, top_hu=top_hu, power=power
    )
    rho_s, rho_bn = float(rho_soft), float(rho_bone)
    w_c = (f_cont * rho_bn) / ((1.0 - f_cont) * rho_s + f_cont * rho_bn)
    w_b = (f_bin * rho_bn) / ((1.0 - f_bin) * rho_s + f_bin * rho_bn)
    mu_c = (1.0 - w_c) * mu_s + w_c * mu_b_end
    mu_disc = (1.0 - w_b) * mu_s + w_b * mu_b_end
    rel = np.abs(mu_disc - mu_c) / np.maximum(mu_c, 1.0e-30)
    imax = int(rel.argmax())
    edges = bone_bin_edges(n_bins, start_hu=start_hu, top_hu=top_hu, power=power)
    return {
        "energy_kev": energy_kev,
        "n_bins": n_bins,
        "spacing": f"uniform in f^(1/{power:g})" if power != 1.0 else "equal-HU",
        "power": float(power),
        "edges_hu": [round(float(x), 1) for x in edges],
        "n_samples": int(n_samples),
        "hu_range": [float(start_hu), float(top_hu)],
        "max_relative_error": float(rel[imax]),
        "max_relative_error_pct": round(float(rel[imax]) * 100.0, 4),
        "at_hu": float(hu[imax]),
        "soft_boundary_relative_error_pct": round(float(rel[0]) * 100.0, 4),
        "f_continuous": float(f_cont[imax]),
        "f_binned": float(f_bin[imax]),
        "w_bone_continuous": float(w_c[imax]),
        "w_bone_binned": float(w_b[imax]),
        "mu_over_rho_soft_cm2_g": mu_s,
        "mu_over_rho_cortical_cm2_g": mu_b_end,
        "mu_over_rho_continuous_cm2_g": float(mu_c[imax]),
        "mu_over_rho_binned_cm2_g": float(mu_disc[imax]),
        "median_relative_error_pct": round(float(np.median(rel)) * 100.0, 4),
        "note": (
            "μ = ρ(HU) × (μ/ρ)_mix at one energy; ρ(HU) is common to both so the "
            "relative error is that of the composition. No Monte Carlo. "
            "Bins are uniform in √f (power=2) so the low-f edge — scored soft "
            "tissue against the bone table — is the finest. "
            "soft_boundary_relative_error_pct is |Δμ/μ| at HU = start (the "
            "scored-organ interface); max_relative_error_pct is the worst "
            "point on the whole [start, top] grid."
        ),
    }


@dataclass(frozen=True)
class TissueGroup:
    """One composition group: an HU interval mapped to one MC-GPU material.

    ``hu_low`` is inclusive, the next group's ``hu_low`` is the exclusive upper
    edge. ``material_file`` and ``nominal_density_g_cm3`` describe the ``.mcgpu``
    file that ``tools/make_materials.py`` produces; the per-voxel density is *not*
    this nominal value but the continuous Schneider HU->rho mapping -- the nominal
    is only what MC-GPU prints and what the material file was generated at.
    """

    name: str
    hu_low: float
    material_file: str
    nominal_density_g_cm3: float
    is_bone: bool = False


def default_tissue_groups(
    *,
    n_bone_bins: int = N_BONE_BINS,
    bone_start_hu: float = BONE_START_HU,
    bone_top_hu: float = BONE_TOP_HU,
    breakpoints_hu: Sequence[float] | None = None,
    density_g_cm3: Sequence[float] | None = None,
) -> tuple[TissueGroup, ...]:
    """The default Schneider group table: 4 merged soft groups + graded bone.

    Soft side (merged -- Z is nearly constant across soft tissues):
        air, lung, adipose, soft tissue.
    Bone side (kept separate -- Z rises with mineral fraction, and that is exactly
    what the photoelectric term is sensitive to): ``n_bone_bins`` bins from
    ``bone_start_hu`` to ``bone_top_hu``, spaced uniformly in √f so the finest
    bins sit at the scored-soft-tissue boundary.

    The total is ``4 + n_bone_bins`` and must not exceed MC-GPU's MAX_MATERIALS.
    The default 4 + 11 = 15 fills the cap; three spare slots over the equal-HU
    8-bin table go to the low-f edge rather than to cortical bone. Nominal
    densities are the Schneider density at each bin midpoint so the generated
    material file is representative.
    """
    if n_bone_bins < 1:
        raise ValueError("need at least one bone bin")
    total = 4 + n_bone_bins
    if total > MCGPU_MAX_MATERIALS:
        raise ValueError(
            f"{total} materials exceeds MAX_MATERIALS={MCGPU_MAX_MATERIALS}; "
            "reduce n_bone_bins (soft groups are already merged; bone groups must not be)"
        )

    def rho(hu: float) -> float:
        return round(float(hu_to_density(np.asarray([hu]), *(
            (breakpoints_hu, density_g_cm3) if breakpoints_hu is not None else ()
        ))[0]), 4)

    # File names and nominal densities match tools/make_materials.py output pinned
    # in materials/PROVENANCE.json. The nominal density is only what the material
    # file was generated at; the per-voxel density is the continuous Schneider value.
    soft = [
        TissueGroup("air", float("-inf"), "air_5-120keV.mcgpu.gz", 0.00120479),
        TissueGroup("lung", -900.0, "lung_5-120keV.mcgpu.gz", 0.3),
        TissueGroup("adipose", -200.0, "adipose_5-120keV.mcgpu.gz", 0.92),
        TissueGroup("soft_tissue", -30.0, "soft_tissue_5-120keV.mcgpu.gz", 1.0),
    ]
    edges = bone_bin_edges(n_bone_bins, start_hu=bone_start_hu, top_hu=bone_top_hu)
    bone: list[TissueGroup] = []
    for k in range(n_bone_bins):
        lo, hi = float(edges[k]), float(edges[k + 1])
        mid = 0.5 * (lo + hi)
        bone.append(
            TissueGroup(
                name=f"bone_{k + 1}",
                hu_low=lo,
                material_file=f"bone_{k + 1}_5-120keV.mcgpu.gz",
                nominal_density_g_cm3=rho(mid),
                is_bone=True,
            )
        )
    return tuple(soft + bone)


def tissue_group_materials(groups: Sequence[TissueGroup]) -> tuple[Material, ...]:
    """1-based :class:`Material` list in group order, ready for the input file."""
    if len(groups) > MCGPU_MAX_MATERIALS:
        raise ValueError(
            f"{len(groups)} groups exceeds MAX_MATERIALS={MCGPU_MAX_MATERIALS}"
        )
    return tuple(
        Material(i + 1, g.name, g.material_file, g.nominal_density_g_cm3)
        for i, g in enumerate(groups)
    )


def assign_material_index(
    hu: np.ndarray, body: np.ndarray, groups: Sequence[TissueGroup]
) -> np.ndarray:
    """Per-voxel 1-based material index: HU -> composition group, air outside body.

    Everything outside the body contour is air (group 1). Inside, the HU is placed
    in the group whose ``hu_low`` interval contains it; values above the top bone
    bin are held in the cortical (top) group -- those are metal/contrast the
    eligibility criterion already screens, kept here only so a stray voxel maps to a
    defined material rather than crashing the write.
    """
    lower = np.asarray([g.hu_low for g in groups], dtype=float)
    if not np.all(np.diff(lower) > 0):
        raise ValueError("tissue group hu_low edges must be strictly increasing")
    if groups[0].name != "air":
        raise ValueError("group 0 must be air (voxels outside the body map to it)")
    idx = np.searchsorted(lower, np.asarray(hu, dtype=float), side="right") - 1
    np.clip(idx, 0, len(groups) - 1, out=idx)
    idx = idx + 1  # 1-based
    idx = np.where(np.asarray(body, dtype=bool), idx, 1)  # outside body -> air
    return idx.astype(np.int32)


def resample_isotropic(
    array: np.ndarray,
    spacing_zyx_mm: tuple[float, float, float],
    *,
    iso_mm: float = DOSE_GRID_MM,
    order: int,
) -> np.ndarray:
    """Zoom a ``(z, y, x)`` array from its native spacing onto an isotropic grid.

    ``order=1`` (linear, volume-conserving-ish) for HU/density, ``order=0``
    (nearest) for label maps. ``mode='nearest'`` so edge voxels are not darkened by
    zero padding.
    """
    from scipy import ndimage

    sz, sy, sx = (float(s) for s in spacing_zyx_mm)
    factors = (sz / iso_mm, sy / iso_mm, sx / iso_mm)
    return ndimage.zoom(np.asarray(array), factors, order=order, mode="nearest")


def build_patient_phantom(
    volume_hu: np.ndarray,
    spacing_zyx_mm: tuple[float, float, float],
    *,
    iso_mm: float = DOSE_GRID_MM,
    groups: Sequence[TissueGroup] | None = None,
    breakpoints_hu: Sequence[float] | None = None,
    density_g_cm3: Sequence[float] | None = None,
    focal_box_xy_cm: float | None = FOCAL_BOX_XY_CM,
) -> tuple[VoxelPhantom, dict]:
    """Native HU volume -> a 2.5 mm :class:`VoxelPhantom` with Schneider materials.

    The HU volume is resampled to ``iso_mm`` first (order-1), then the body contour,
    Schneider density and composition groups are all derived on the isotropic grid,
    so materials and density are mutually consistent on the grid the Monte Carlo
    actually runs on. The in-plane extent is then padded with air to
    ``focal_box_xy_cm`` (default 130 cm) so the focal spot at SAD sits *inside*
    the voxel box (G3). Returns ``(phantom, report)``.
    """
    groups = tuple(groups) if groups is not None else default_tissue_groups()
    hu_iso = resample_isotropic(volume_hu, spacing_zyx_mm, iso_mm=iso_mm, order=1)

    kw: dict = {}
    if breakpoints_hu is not None and density_g_cm3 is not None:
        kw = {"breakpoints_hu": breakpoints_hu, "density_g_cm3": density_g_cm3}
    body = body_contour(hu_iso)
    density, body, report = patient_density_map(hu_iso, body=body, **kw)
    material = assign_material_index(hu_iso, body, groups)

    phantom = VoxelPhantom(
        material=material,
        density=density.astype(np.float64),
        voxel_size_cm=(iso_mm / 10.0, iso_mm / 10.0, iso_mm / 10.0),
        materials=tissue_group_materials(groups),
    )
    pad: tuple[int, int, int] = (0, 0, 0)
    if focal_box_xy_cm is not None:
        phantom, pad = embed_in_focal_box(phantom, xy_cm=focal_box_xy_cm)
    report = dict(report)
    report.update(
        {
            "iso_grid_mm": iso_mm,
            "native_spacing_mm_zyx": [round(float(s), 4) for s in spacing_zyx_mm],
            "patient_shape_zyx": [int(n) for n in hu_iso.shape],
            "resampled_shape_zyx": [int(n) for n in phantom.shape_zyx],
            "focal_box_xy_cm": focal_box_xy_cm,
            "pad_before_zyx": list(pad),
            "n_materials": len(groups),
            "material_names": [g.name for g in groups],
        }
    )
    return phantom, report


def embed_in_focal_box(
    phantom: VoxelPhantom, *, xy_cm: float = FOCAL_BOX_XY_CM
) -> tuple[VoxelPhantom, tuple[int, int, int]]:
    """Pad *xy* with air so the in-plane box is ``xy_cm``; z is unchanged.

    G3 requires the voxel box to contain the focal spot. A 60 cm SAD needs ~130 cm
    in-plane; the native reconstructed FOV is ~30–50 cm. Z only has to cover the
    scan length. Returns ``(padded, pad_before_zyx)`` so organ masks can be shifted
    onto the same grid with :func:`pad_mask`.
    """
    dx, dy, dz = phantom.voxel_size_cm
    nz, ny, nx = phantom.shape_zyx
    want_x = int(round(xy_cm / dx))
    want_y = int(round(xy_cm / dy))
    if want_x < nx or want_y < ny:
        raise ValueError(
            f"focal box {xy_cm} cm is smaller than the patient grid "
            f"{nx * dx:.1f} x {ny * dy:.1f} cm"
        )
    pad_x0 = (want_x - nx) // 2
    pad_y0 = (want_y - ny) // 2
    pad_x1 = want_x - nx - pad_x0
    pad_y1 = want_y - ny - pad_y0
    if pad_x0 == 0 and pad_y0 == 0 and pad_x1 == 0 and pad_y1 == 0:
        return phantom, (0, 0, 0)
    air_index = 1  # group 0 is air
    air_rho = min(m.nominal_density_g_cm3 for m in phantom.materials)
    material = np.pad(
        phantom.material,
        ((0, 0), (pad_y0, pad_y1), (pad_x0, pad_x1)),
        mode="constant",
        constant_values=air_index,
    )
    density = np.pad(
        phantom.density,
        ((0, 0), (pad_y0, pad_y1), (pad_x0, pad_x1)),
        mode="constant",
        constant_values=air_rho,
    )
    padded = VoxelPhantom(
        material=material,
        density=density,
        voxel_size_cm=phantom.voxel_size_cm,
        materials=phantom.materials,
    )
    return padded, (0, pad_y0, pad_x0)


def pad_mask(
    mask: np.ndarray, pad_before_zyx: tuple[int, int, int], shape_zyx: tuple[int, int, int]
) -> np.ndarray:
    """Place a patient-grid mask onto the padded focal-box grid."""
    out = np.zeros(shape_zyx, dtype=bool)
    z0, y0, x0 = (int(v) for v in pad_before_zyx)
    nz, ny, nx = mask.shape
    out[z0 : z0 + nz, y0 : y0 + ny, x0 : x0 + nx] = np.asarray(mask, dtype=bool)
    return out


def organ_bounding_box(
    mask: np.ndarray, *, pad_voxels: int = 1
) -> tuple[tuple[int, int], tuple[int, int], tuple[int, int]]:
    """1-based inclusive ``((x0,x1),(y0,y1),(z0,z1))`` ROI around a ``(z,y,x)`` mask.

    MC-GPU's dose ROI is 1-based and given X,Y,Z. Scoring only the organ's box keeps
    the tally small: G2 buried the signal under 226 MB of full-volume dose I/O, and
    the patient grid is larger still. ``pad_voxels`` gives a one-voxel skirt so a
    boundary organ is not clipped by the resampling.
    """
    m = np.asarray(mask, dtype=bool)
    if not m.any():
        raise ValueError("empty mask has no bounding box")
    nz, ny, nx = m.shape
    zs, ys, xs = np.where(m)

    def span(lo: int, hi: int, n: int) -> tuple[int, int]:
        lo = max(0, int(lo) - pad_voxels)
        hi = min(n - 1, int(hi) + pad_voxels)
        return lo + 1, hi + 1  # 1-based inclusive

    return (
        span(xs.min(), xs.max(), nx),
        span(ys.min(), ys.max(), ny),
        span(zs.min(), zs.max(), nz),
    )


def union_organ_roi(
    masks: dict[str, np.ndarray], *, pad_voxels: int = 1
) -> tuple[tuple[int, int], tuple[int, int], tuple[int, int]]:
    """1-based inclusive ROI covering every non-empty organ mask.

    The dose tally is this box, not the 130 cm volume: G2 buried its signal under
    226 MB of full-volume I/O, and the patient grid is larger still.
    """
    if not masks:
        raise ValueError("no organ masks")
    combined = None
    for m in masks.values():
        b = np.asarray(m, dtype=bool)
        combined = b if combined is None else (combined | b)
    if combined is None or not combined.any():
        raise ValueError("every organ mask is empty")
    return organ_bounding_box(combined, pad_voxels=pad_voxels)
