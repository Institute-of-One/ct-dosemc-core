"""Patient voxel phantom: geometry and material assignment for Phase-2 dose runs.

This is the (a) patient driver's front end. Two things are settled here, both of
which the physics depends on and neither of which may be assumed silently:

Geometry -- the dose grid is isotropic **2.5 mm**, not the native ~0.7 mm image.
    G3 requires the air box to reach the focal spot, i.e. a ~130 cm box; at 0.7 mm
    that is ~2.4e9 voxels, which is not runnable. At 2.5 mm the same box is
    ~520x520x200 = 5.4e7 voxels -- about twice the G2 phantom, and the *same*
    0.25 cm at which G2/G3 convergence was measured, so the voxel-size systematic
    term carries over. The mass cost of resampling is measured, not assumed
    (``tools/resample_cost.py``): <~1% median for the scored abdominal organs.

Materials -- Schneider tissue *groups*, not density bins.
    The photoelectric cross-section scales as ~Z^3-4, so a voxel's composition
    (its Z), not just its density, sets its dose; merging bone and soft tissue
    into one material makes bone dose wrong by an order of magnitude and, through
    the scattered field, biases the dose to neighbouring organs. Each voxel is
    therefore assigned a *composition* group by HU, while its density stays the
    continuous Schneider HU->rho value. Soft-tissue groups may be merged (Z barely
    moves); bone groups may not (Z is exactly what moves). MC-GPU v1.3 is built with
    MAX_MATERIALS=15, so the group count is capped there. Metal is out of the
    Schneider calibration and is removed by the eligibility criterion upstream, so
    the material set only has to span air -> cortical bone.

The actual ``.mcgpu`` material files are generated by ``tools/make_materials.py``
from PENDBASE and pinned by SHA-256 in ``materials/PROVENANCE.json``; this module
references them by name and nominal density and never invents a composition.
"""

