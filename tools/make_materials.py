"""Generate the MC-GPU material files this project needs, from open data.

MC-GPU v1.3's own repository ships only a dozen materials, none of which is PMMA,
air or water -- the three the CTDI anchor needs.  Rather than transcribe a
proprietary table, the files are *generated* from the PENELOPE 2006 photon
cross-section database using Andreu Badal's ``MCGPU_materials`` utility, which
carries the permissive Universitat de Barcelona notice reproduced in
``docs/MC_SOURCE_MODEL.md``.

That keeps the openness claim intact end to end: engine (public domain), material
data (permissive, redistributable), spectra (BSD-3), wrapper (MIT).

Usage::

    python tools/make_materials.py                 # all default materials
    python tools/make_materials.py --only PMMA air

Prerequisites: ``vendor/MCGPU_materials`` cloned and its executable built (the
script builds it if gfortran is on PATH or under ``vendor/mingw64/bin``).
"""

from __future__ import annotations

import argparse
import gzip
import json
import os
import shutil
import subprocess
import sys
from dataclasses import dataclass
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(REPO))

from ct_dosemc_core.provenance import environment, file_digest  # noqa: E402

GENERATOR_REPO = "https://github.com/andreubs/MCGPU_materials"
VENDOR = REPO / "vendor" / "MCGPU_materials"
MATERIALS_DIR = REPO / "materials"


@dataclass(frozen=True)
class MaterialSpec:
    """One material, identified by its PENELOPE ``pdcompos.p06`` entry.

    Using the database entry rather than typing a composition by hand means the
    elemental composition and density are the published ICRU/NIST ones and are
    traceable to a line number in a file that ships with the generator.
    """

    name: str
    pendbase_id: int
    pendbase_label: str
    insulator: bool = True

    def input_deck(self, e_min_ev: int, e_max_ev: int, step_ev: int, out_name: str) -> str:
        return "\n".join(
            [
                "2",  # read composition from PENDBASE_photons/pdcompos.p06
                str(self.pendbase_id),
                "1" if self.insulator else "2",
                f"{e_min_ev} {e_max_ev}",
                str(step_ev),
                out_name,
                "",
            ]
        )


MATERIALS: tuple[MaterialSpec, ...] = (
    MaterialSpec("PMMA", 224, "POLYMETHYL METHACRALATE (LUCITE, PERSPEX, PLEXIGLASS)"),
    MaterialSpec("air", 104, "AIR, DRY (NEAR SEA LEVEL)"),
    MaterialSpec("water", 278, "WATER, LIQUID"),
    # -- Phase-2 patient tissue set --------------------------------------------
    # The soft-tissue side of the Schneider group table. Each is a named ICRP
    # tissue read straight from pdcompos.p06, so the composition is the published
    # one and traceable to a line number. Soft tissues may be merged (their Z
    # barely moves); the cortical-bone endpoint anchors the graded bone series
    # generated by BONE_MIXES below. See ct_dosemc_core.patient for the HU bins.
    MaterialSpec("lung", 191, "LUNG (ICRP)"),
    MaterialSpec("adipose", 103, "ADIPOSE TISSUE (ICRP)"),
    MaterialSpec("soft_tissue", 262, "TISSUE, SOFT (ICRP)"),
    MaterialSpec("bone_cortical", 120, "BONE, CORTICAL (ICRP)"),
)

# -- graded bone by Schneider's two-endpoint stoichiometric interpolation ------
# PENELOPE's pdcompos names exactly one bone tissue (cortical, ICRP 120) and one
# compact bone (ICRU 119); it has no spongiosa/marrow gradation. Schneider (2000)
# places CT number on the *volume* fraction of the mineral endpoint, because μ is
# linear in volume fraction (μ_mix = (1-f) μ_soft + f μ_bone) and HU ∝ μ. The
# elemental *weight* fractions are then derived by density weighting:
#     ρ_mix = (1-f) ρ_soft + f ρ_bone
#     w_bone = f · ρ_bone / ρ_mix
# Mixing weight fractions linearly with HU understates the bone component by
# ~30% at mid-bin (w = 0.651 at f = 0.5, not 0.500) and the photoelectric
# cross-section (~Z^3.5) by 20–30%. The two endpoints are ICRP compositions;
# only f is ours, and it is recorded per bin in PROVENANCE.json.
SOFT_ENDPOINT_ID = 262   # TISSUE, SOFT (ICRP)
BONE_ENDPOINT_ID = 120   # BONE, CORTICAL (ICRP)


def _gfortran() -> str:
    local = REPO / "vendor" / "mingw64" / "bin" / "gfortran.exe"
    if local.is_file():
        return str(local)
    found = shutil.which("gfortran")
    if found:
        return found
    raise SystemExit(
        "gfortran not found. Either put it on PATH or unpack a MinGW-w64 build "
        f"into {REPO / 'vendor' / 'mingw64'} (see docs/MC_SOURCE_MODEL.md)."
    )


def _executable() -> Path:
    if not VENDOR.is_dir():
        raise SystemExit(
            f"{VENDOR} is missing. Clone it first:\n"
            f"    git clone --depth 1 {GENERATOR_REPO} {VENDOR}"
        )
    exe = VENDOR / ("MCGPU_materials.exe" if os.name == "nt" else "MCGPU_materials.x")
    if exe.is_file():
        return exe
    print(f"[make_materials] building the generator -> {exe.name}")
    subprocess.run(
        [_gfortran(), "MCGPU_materials.f", "penelope_photons.f", "-o", exe.name, "-O2"],
        cwd=str(VENDOR),
        check=True,
    )
    return exe


def generate(
    spec: MaterialSpec,
    exe: Path,
    *,
    e_min_ev: int,
    e_max_ev: int,
    step_ev: int,
    compress: bool,
) -> dict[str, object]:
    stem = f"{spec.name}_{e_min_ev // 1000}-{e_max_ev // 1000}keV"
    raw_name = f"{stem}.mcgpu"
    deck = VENDOR / f"_deck_{spec.name}.txt"
    deck.write_text(spec.input_deck(e_min_ev, e_max_ev, step_ev, raw_name), encoding="ascii")

    env = dict(os.environ)
    mingw_bin = REPO / "vendor" / "mingw64" / "bin"
    if mingw_bin.is_dir():
        env["PATH"] = f"{mingw_bin}{os.pathsep}{env.get('PATH', '')}"

    with deck.open("rb") as fh:
        proc = subprocess.run(
            [str(exe)], cwd=str(VENDOR), stdin=fh, capture_output=True, text=True, env=env
        )
    if "correctly generated" not in proc.stdout:
        raise SystemExit(
            f"generator failed for {spec.name}:\n{proc.stdout[-2000:]}\n{proc.stderr[-2000:]}"
        )
    # The generator echoes the entry it resolved; refuse a silent mismatch, which
    # is how you end up simulating photographic emulsion instead of PMMA.
    if spec.pendbase_label.split()[0] not in proc.stdout:
        raise SystemExit(
            f"PENDBASE id {spec.pendbase_id} did not resolve to {spec.pendbase_label!r}:\n"
            + "\n".join(line for line in proc.stdout.splitlines() if str(spec.pendbase_id) in line)
        )

    density = None
    for line in proc.stdout.splitlines():
        if "Density" in line:
            density = float(line.split("=")[1].split()[0])
            break

    produced = VENDOR / raw_name
    MATERIALS_DIR.mkdir(parents=True, exist_ok=True)
    target = MATERIALS_DIR / (raw_name + ".gz" if compress else raw_name)
    if compress:
        with produced.open("rb") as src, gzip.open(target, "wb", compresslevel=9) as dst:
            shutil.copyfileobj(src, dst)
    else:
        shutil.copy2(produced, target)
    produced.unlink()
    deck.unlink()

    return {
        "material": spec.name,
        "file": target.name,
        "sha256": file_digest(target),
        "pendbase_id": spec.pendbase_id,
        "pendbase_label": spec.pendbase_label,
        "nominal_density_g_cm3": density,
        "insulator": spec.insulator,
        "energy_range_ev": [e_min_ev, e_max_ev],
        "energy_step_ev": step_ev,
    }


def _pendbase_composition(pendbase_id: int) -> tuple[str, float, list[tuple[int, float]]]:
    """Parse ``pdcompos.p06`` for one material: (name, density, [(Z, weight_fraction)]).

    The file's first 15 lines are a preamble; each material block is a header line
    ``IORD  NAME``, a line ``NELEM  Z/A  I(eV)  density``, then NELEM lines
    ``Z  weight_fraction  stoichiometric_index`` (the middle column is the fraction
    by weight, per the file's own header). Parsed exactly as the generator's own
    option-2 reader does, so the fractions we mix are the published ICRP ones.
    """
    path = VENDOR / "PENDBASE_photons" / "pdcompos.p06"
    lines = path.read_text(encoding="latin-1").splitlines()
    i = 15  # skip preamble
    while i < len(lines):
        header = lines[i]
        try:
            iord = int(header[:3])
        except ValueError:
            i += 1
            continue
        name = header[5:].strip()
        nelem_tok = lines[i + 1].split()
        nelem = int(nelem_tok[0])
        density = float(nelem_tok[3])
        elems: list[tuple[int, float]] = []
        for j in range(nelem):
            z_tok = lines[i + 2 + j].split()
            elems.append((int(z_tok[0]), float(z_tok[1])))
        if iord == pendbase_id:
            return name, density, elems
        i += 2 + nelem
    raise SystemExit(f"PENDBASE id {pendbase_id} not found in {path}")


def generate_bone_mix(
    name: str,
    fractions: list[tuple[int, float]],
    nominal_density: float,
    exe: Path,
    *,
    e_min_ev: int,
    e_max_ev: int,
    step_ev: int,
    compress: bool,
) -> Path:
    """Generate one mixed-composition material through the generator's keyboard path."""
    stem = f"{name}_{e_min_ev // 1000}-{e_max_ev // 1000}keV"
    raw_name = f"{stem}.mcgpu"
    deck_lines = [
        "1",  # define material from keyboard
        name[:60],
        str(len(fractions)),
        "2",  # composition given as fractions by weight
    ]
    deck_lines += [f"{z} {frac:.8f}" for z, frac in fractions]
    deck_lines += [
        f"{nominal_density:.8f}",
        "1",  # insulator (tissue)
        f"{e_min_ev} {e_max_ev}",
        str(step_ev),
        raw_name,
        "",
    ]
    deck = VENDOR / f"_deck_{name}.txt"
    deck.write_text("\n".join(deck_lines), encoding="ascii")

    env = dict(os.environ)
    mingw_bin = REPO / "vendor" / "mingw64" / "bin"
    if mingw_bin.is_dir():
        env["PATH"] = f"{mingw_bin}{os.pathsep}{env.get('PATH', '')}"
    with deck.open("rb") as fh:
        proc = subprocess.run(
            [str(exe)], cwd=str(VENDOR), stdin=fh, capture_output=True, text=True, env=env
        )
    if "correctly generated" not in proc.stdout:
        raise SystemExit(
            f"generator failed for {name}:\n{proc.stdout[-2000:]}\n{proc.stderr[-2000:]}"
        )
    produced = VENDOR / raw_name
    MATERIALS_DIR.mkdir(parents=True, exist_ok=True)
    target = MATERIALS_DIR / (raw_name + ".gz" if compress else raw_name)
    if compress:
        with produced.open("rb") as src, gzip.open(target, "wb", compresslevel=9) as dst:
            shutil.copyfileobj(src, dst)
    else:
        shutil.copy2(produced, target)
    produced.unlink()
    deck.unlink()
    return target


def make_bone_series(
    exe: Path,
    *,
    n_bins: int,
    bone_start_hu: float,
    bone_top_hu: float,
    e_min_ev: int,
    e_max_ev: int,
    step_ev: int,
    compress: bool,
) -> list[dict[str, object]]:
    """Generate the graded bone series by soft<->cortical *volume*-fraction mixing.

    Bin edges are uniform in √f (``patient.BONE_BIN_POWER``), so the finest bins
    sit at the scored-soft-tissue boundary. Volume fraction ``f_k`` is linear in
    the bin-midpoint HU (because HU ∝ μ ∝ f). The elemental weight fractions
    follow from density weighting (``mix_by_volume_fraction``); the file's
    nominal density is the Schneider HU→ρ value at the midpoint. ``--bones N``
    shares the same edges as ``patient.default_tissue_groups(n_bone_bins=N)``.
    """
    from ct_dosemc_core.patient import (  # noqa: E402
        BONE_BIN_POWER,
        bone_bin_edges,
        bone_volume_fraction,
        mix_by_volume_fraction,
    )
    from ct_dosemc_core.phantom import hu_to_density  # noqa: E402

    _, rho_soft, soft = _pendbase_composition(SOFT_ENDPOINT_ID)
    _, rho_bone, bone = _pendbase_composition(BONE_ENDPOINT_ID)
    import numpy as np  # noqa: E402

    edges = bone_bin_edges(n_bins, start_hu=bone_start_hu, top_hu=bone_top_hu)
    records: list[dict[str, object]] = []
    for k in range(n_bins):
        lo, hi = float(edges[k]), float(edges[k + 1])
        mid = 0.5 * (lo + hi)
        f_vol = float(bone_volume_fraction(mid, start_hu=bone_start_hu, top_hu=bone_top_hu))
        fractions, rho_mix, w_bone = mix_by_volume_fraction(
            soft, bone, f_vol, rho_soft, rho_bone
        )
        rho = float(hu_to_density(np.asarray([mid]))[0])
        name = f"bone_{k + 1}"
        print(
            f"[make_materials] {name}  HU[{lo:.0f},{hi:.0f}] "
            f"f_vol={f_vol:.3f} w_bone={w_bone:.3f} rho={rho:.3f}"
        )
        target = generate_bone_mix(
            name, fractions, rho, exe,
            e_min_ev=e_min_ev, e_max_ev=e_max_ev, step_ev=step_ev, compress=compress,
        )
        records.append({
            "material": name,
            "file": target.name,
            "sha256": file_digest(target),
            "composition": "Schneider two-endpoint volume-fraction mix",
            "endpoints": {
                "soft_tissue_pendbase_id": SOFT_ENDPOINT_ID,
                "cortical_bone_pendbase_id": BONE_ENDPOINT_ID,
                "rho_soft_g_cm3": rho_soft,
                "rho_cortical_g_cm3": rho_bone,
            },
            "hu_bin": [round(lo, 1), round(hi, 1)],
            "volume_fraction_f": round(f_vol, 4),
            "spacing": "uniform in sqrt(f)",
            "power": float(BONE_BIN_POWER),
            "mass_fraction_bone": round(w_bone, 4),
            "rho_mix_endpoints_g_cm3": round(rho_mix, 4),
            "weight_fractions": {str(z): round(w, 6) for z, w in fractions},
            "nominal_density_g_cm3": round(rho, 4),
            "insulator": True,
            "energy_range_ev": [e_min_ev, e_max_ev],
            "energy_step_ev": step_ev,
        })
    return records


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--only", nargs="*", default=None, help="subset of material names")
    ap.add_argument("--e-min-ev", type=int, default=5_000)
    ap.add_argument("--e-max-ev", type=int, default=120_000)
    ap.add_argument("--step-ev", type=int, default=5)
    ap.add_argument("--no-compress", action="store_true")
    ap.add_argument("--bones", type=int, default=0,
                    help="also generate this many graded bone bins (soft<->cortical mix)")
    ap.add_argument("--bone-start-hu", type=float, default=100.0)
    ap.add_argument("--bone-top-hu", type=float, default=3000.0)
    ap.add_argument("--only-bones", action="store_true",
                    help="generate only the bone series, skip the named tissues")
    args = ap.parse_args(argv)

    wanted = MATERIALS
    if args.only:
        names = {n.lower() for n in args.only}
        wanted = tuple(m for m in MATERIALS if m.name.lower() in names)
        unknown = names - {m.name.lower() for m in MATERIALS}
        if unknown:
            raise SystemExit(f"unknown material(s): {sorted(unknown)}")
    if args.only_bones:
        wanted = ()

    exe = _executable()
    records = []
    for spec in wanted:
        print(f"[make_materials] {spec.name} (PENDBASE #{spec.pendbase_id})")
        records.append(
            generate(
                spec,
                exe,
                e_min_ev=args.e_min_ev,
                e_max_ev=args.e_max_ev,
                step_ev=args.step_ev,
                compress=not args.no_compress,
            )
        )

    if args.bones:
        records.extend(
            make_bone_series(
                exe,
                n_bins=args.bones,
                bone_start_hu=args.bone_start_hu,
                bone_top_hu=args.bone_top_hu,
                e_min_ev=args.e_min_ev,
                e_max_ev=args.e_max_ev,
                step_ev=args.step_ev,
                compress=not args.no_compress,
            )
        )

    manifest = MATERIALS_DIR / "PROVENANCE.json"
    existing = json.loads(manifest.read_text(encoding="utf-8")) if manifest.is_file() else {}
    # Key by file, not material name: 5-120 keV and 5-150 keV of the same
    # tissue must coexist. The 120 keV set stays the Phase-1a / ≤120 kVp path.
    by_file = {r["file"]: r for r in existing.get("materials", [])}
    by_file.update({r["file"]: r for r in records})
    manifest.write_text(
        json.dumps(
            {
                "environment": environment(REPO),
                "generator": {
                    "repository": GENERATOR_REPO,
                    "program": "MCGPU_materials.f + penelope_photons.f",
                    "database": "PENDBASE_photons (photon-only subset of PENELOPE 2006 PENDBASE)",
                    "licence": "Universitat de Barcelona permissive notice; see "
                    "docs/MC_SOURCE_MODEL.md",
                    "reference": "F. Salvat, J. M. Fernandez-Varea, J. Sempau, PENELOPE -- "
                    "A code system for Monte Carlo simulation of electron and photon "
                    "transport, NEA-OECD (2006)",
                },
                "materials": sorted(by_file.values(), key=lambda r: str(r["file"])),
            },
            indent=2,
        ),
        encoding="utf-8",
    )
    print(f"[make_materials] wrote {manifest}")
    for r in records:
        print(f"    {r['material']:6s} rho={r['nominal_density_g_cm3']}  {r['file']}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
